/**
 * Writes content/bank/report.md: what clinicians need to fix in the sheets, and the full list of ids
 * that red-flag rules and translations refer to.
 */
import type { Bank } from "@setu/bank";
import type { Diagnostic, Diagnostics } from "./diagnostics";

function table(items: Diagnostic[]): string {
  if (items.length === 0) return "_None._\n";
  const esc = (s: string) => s.replace(/\|/g, "\\|");
  return ["| Where | Problem |", "| --- | --- |", ...items.map((d) => `| ${esc(d.where)} | ${esc(d.message)} |`)].join("\n") + "\n";
}

export function renderReport(bank: Bank | undefined, diag: Diagnostics): string {
  const errors = diag.items.filter((d) => d.severity === "error");
  const warnings = diag.items.filter((d) => d.severity === "warning");
  const corrections = diag.items.filter((d) => d.severity === "correction");
  const out: string[] = [];
  out.push("# Question bank build report", "");
  out.push("Generated by `pnpm bank:build`. Do not edit by hand.", "");
  if (bank) out.push(`Bank version \`${bank.version}\`: ${bank.complaints.length} complaints, ${bank.complaints.reduce((n, c) => n + c.questions.length, 0)} complaint questions, ${bank.pastHistory.questions.length} past-history and ${bank.personalHistory.questions.length} personal-history questions, ${bank.redFlags.length} red-flag rules.`, "");
  else out.push("**The build failed. Fix the errors below.**", "");
  out.push(`## Errors (${errors.length})`, "", table(errors));
  out.push(`## Corrections applied (${corrections.length})`, "", "These were fixed by `corrections.yaml`. Please also fix them in the sheet.", "", table(corrections));
  out.push(`## Warnings (${warnings.length})`, "", "Things that look wrong or unclear in the content. The build still works.", "", table(warnings));

  if (bank) {
    out.push("## Ids", "", "Use these ids in `red-flags.yaml`, `codes.yaml` and translations.", "");
    for (const c of bank.complaints) {
      out.push(`### ${c.name.en} \`${c.id}\` (group \`${c.groupId}\`)`, "");
      for (const q of c.questions) {
        const opts = q.options.map((o) => `\`${o.id}\`${o.triggersComplaint ? ` → ${o.triggersComplaint}` : ""}`).join(", ");
        out.push(`- \`${q.id}\` (${q.kind})${opts ? `: ${opts}` : ""}`);
      }
      out.push("");
    }
  }
  return out.join("\n");
}
